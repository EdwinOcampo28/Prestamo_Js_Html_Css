const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(require('node:path').join(__dirname, '..', 'app.js'), 'utf8');
const end = source.indexOf('function formData(form)');
assert.ok(end > 0, 'No se encontró el adaptador local');
const values = new Map();
const localStorage = { getItem: k => values.has(k) ? values.get(k) : null, setItem: (k,v) => values.set(k, String(v)), removeItem: k => values.delete(k) };
const context = { localStorage, Math, Date, JSON, Number, String, Array, Object, RegExp, Error, Intl, Map, Set, console };
vm.createContext(context);
vm.runInContext(source.slice(0, end) + '\nglobalThis.apiTest = api;', context);
const api = context.apiTest;
(async () => {
  assert.equal((await api('/bootstrap')).setup_required, true);
  await api('/setup', {method:'POST', body:{nombre:'Admin Prueba', usuario:'admin_demo', password:'ClavePrueba123'}});
  await api('/logout', {method:'POST', body:{}});
  await api('/register', {method:'POST', body:{nombre:'Cliente Prueba', usuario:'cliente_demo', documento:'DOC001', password:'Cliente12345', correo:'cliente@demo.com'}});
  await assert.rejects(() => api('/register', {method:'POST', body:{nombre:'Duplicado', usuario:'cliente_demo', password:'Cliente12345'}}), /ya existe/);
  await api('/login', {method:'POST', body:{usuario:'cliente_demo', password:'Cliente12345'}});
  const request = await api('/requests', {method:'POST', body:{monto:'1200000', meses:'12', motivo:'Prueba ficticia'}});
  assert.equal(request.id, 1);
  await assert.rejects(() => api('/requests/1/decision', {method:'POST', body:{decision:'aprobar', tasa:'2'}}), /permiso/);
  await api('/logout', {method:'POST', body:{}});
  await api('/login', {method:'POST', body:{usuario:'admin_demo', password:'ClavePrueba123'}});
  const inbox = await api('/requests');
  assert.equal(inbox.requests[0].estado, 'pendiente');
  const approved = await api('/requests/1/decision', {method:'POST', body:{decision:'aprobar', tasa:'2', nota:'Aprobado en prueba'}});
  assert.equal(approved.loan_id, 1);
  let detail = await api('/loans/1');
  assert.equal(detail.quotas.length, 12);
  assert.equal(detail.loan.tasa, 0.02);
  const firstQuota = detail.quotas[0];
  // Payment operations belong to the borrower, not the administrator.
  await assert.rejects(() => api('/loans/1/payment', {method:'POST', body:{cuota_id:firstQuota.id, monto:firstQuota.cuota}}), /permiso/);
  await api('/logout', {method:'POST', body:{}});
  await api('/login', {method:'POST', body:{usuario:'cliente_demo', password:'Cliente12345'}});
  await api('/loans/1/payment', {method:'POST', body:{cuota_id:firstQuota.id, monto:firstQuota.cuota}});
  detail = await api('/loans/1');
  assert.equal(detail.quotas[0].estado, 'pagada');
  assert.equal(detail.movements.length, 1);
  assert.equal(detail.movements[0].usuario, undefined); // movement keeps finance data; actor is recorded in audit
  const before = detail.loan.saldo;
  await api('/loans/1/extra-payment', {method:'POST', body:{monto:10000, modo:'cuota'}});
  detail = await api('/loans/1');
  assert.equal(detail.loan.saldo, before - 10000);
  await api('/logout', {method:'POST', body:{}});
  await api('/login', {method:'POST', body:{usuario:'admin_demo', password:'ClavePrueba123'}});
  assert.equal((await api('/reports')).monthly.length, 1);
  const audit = (await api('/audit')).audit;
  assert.ok(audit.length >= 5);
  assert.ok(audit.some(a=>a.accion==='PAGO DE CUOTA'&&a.usuario==='cliente_demo'));
  assert.ok(audit.some(a=>a.accion==='ABONO EXTRAORDINARIO'&&a.usuario==='cliente_demo'));
  const backup = await api('/backup');
  assert.equal(backup.data.loans.length, 1);
  await api('/register', {method:'POST', body:{nombre:'Cliente Temporal', usuario:'cliente_temporal', password:'Temporal12345'}});
  const clientsBefore = (await api('/clients')).clients;
  const temporary = clientsBefore.find(c=>c.usuario==='cliente_temporal');
  assert.ok(temporary);
  const deleted = await api(`/clients/${temporary.id}`, {method:'POST', body:{}});
  assert.equal(deleted.deactivated, false);
  assert.ok(!(await api('/clients')).clients.some(c=>c.id===temporary.id));
  const retained = await api('/clients/2', {method:'POST', body:{}});
  assert.equal(retained.deactivated, true);
  assert.equal((await api('/loans')).loans.length, 1);
  assert.equal((await api('/requests')).requests[0].cliente_nombre, 'Cliente Prueba');
  assert.ok(source.includes("data-action=\"approve-from-modal\""), 'El botón de aprobación debe usar el manejador explícito de clic');
  assert.ok(source.includes("data-action=\"delete-client\""), 'La tabla de clientes debe mostrar la acción de eliminar');
  assert.ok(source.includes("data-page=\"backups\"" ) || source.includes("['backups','⇧','Copias de seguridad']"), 'Debe existir el módulo de copias de seguridad');
  assert.ok(source.includes("data-action=\"import-backup\""), 'Debe existir la acción para importar respaldos');
  assert.ok(source.includes("data-action=\"reset-all-data\""), 'Debe existir la acción para eliminar todos los datos');
  const fullBackup = await api('/backup');
  await api('/register', {method:'POST', body:{nombre:'Temporal para restaurar', usuario:'temp_restore', password:'Temporal12345'}});
  assert.equal(fullBackup.format, 'PRESTAMO_PLUS_BACKUP');
  assert.ok(fullBackup.data.users.length >= 2);
  await assert.rejects(() => api('/backup/import', {method:'POST',body:{format:'PRESTAMO_PLUS_BACKUP',data:{version:2,users:[]}}}), /incompleto/);
  const imported = await api('/backup/import', {method:'POST',body:fullBackup});
  assert.ok(imported.counts.users >= 2);
  assert.ok((await api('/clients')).clients.some(c=>c.usuario==='cliente_demo'));
  assert.ok(!(await api('/clients')).clients.some(c=>c.usuario==='temp_restore')); 
  await assert.rejects(() => api('/system/reset', {method:'POST',body:{confirmation:'NO'}}), /ELIMINAR TODO/);
  const reset = await api('/system/reset', {method:'POST',body:{confirmation:'ELIMINAR TODO'}});
  assert.equal(reset.reset, true);
  assert.equal((await api('/bootstrap')).setup_required, true);
  console.log('PASS: registro, login, duplicados, permisos, solicitudes, aprobación, cuotas, pago, abono, reportes, auditoría, exportación/importación validada, eliminación segura de clientes y reinicio total protegido.');
})().catch(err => { console.error(err); process.exit(1); });
